#!/usr/bin/env python3
"""Generate lib/data/mock/mock_seed.dart from scripts/seed/*.json (fictional data).

Run from frontend/:  python3 tool/gen_mock_seed.py
The mock backend (USE_MOCK=true) uses it until the real backend is merged (G1).
"""
import json
from pathlib import Path

SEED = Path(__file__).resolve().parents[2] / "scripts" / "seed"
OUT = Path(__file__).resolve().parents[1] / "lib" / "data" / "mock" / "mock_seed.dart"


def load(name):
    return json.loads((SEED / name).read_text(encoding="utf-8"))


def lit(v):
    """Dart literal of a JSON value."""
    return json.dumps(v, ensure_ascii=False).replace("$", "\\$")


branches = load("branches.json")
std = branches["standard_hours"]
items = []
for b in branches["items"]:
    items.append({k: b[k] for k in ("id", "name", "province", "town", "address", "phone", "services")} | {"hours": b.get("hours", std)})

personas = [
    {k: c[k] for k in ("full_name", "phone", "account_number", "pin", "date_of_birth", "language", "cards")}
    for c in load("demo_credentials.json")["items"][:5]
]

out = [
    "// GENERATED by tool/gen_mock_seed.py from scripts/seed — do not edit by hand.",
    "// FICTIONAL DEMO DATA only (synthetic names, accounts, phones, branches, products).",
    "// Used by the mock backend (USE_MOCK=true), which is tree-shaken out of real builds.",
    "// ignore_for_file: lines_longer_than_80_chars",
    "",
    f"const kMockAgents = <Map<String, dynamic>>{lit(load('agents.json')['items'])};",
    "",
    f"const kMockBranches = <Map<String, dynamic>>{lit(items)};",
    "",
    f"const kMockLoanProducts = <Map<String, dynamic>>{lit(load('loan_products.json')['items'])};",
    "",
    f"const kMockKbArticles = <Map<String, dynamic>>{lit(load('kb_articles.json')['articles'])};",
    "",
    "/// The 5 demo personas of scripts/seed/demo_credentials.json (synthetic PINs for the demo only).",
    f"const kMockPersonas = <Map<String, dynamic>>{lit(personas)};",
    "",
]
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(out), encoding="utf-8")
print(f"wrote {OUT}")
